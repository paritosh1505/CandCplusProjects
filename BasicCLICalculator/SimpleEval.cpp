
#include<cmath>
double Addition(int a, int b){
    return a+b;
}
double Subtraction(int a, int b){
    return a-b;
}
double Multiply(int a, int b){
    return a*b;
}
double Divison(int a, int b){
    return a/b;
}
double Modulos(int a, int b){
    return a%b;
}

double SqaureVal(int a){
    return a^2;
}
double PowerVal(int a, int b){
    return pow(a,b);
}